-- geo/fcc_bdc/schema_v2.sql
--
-- The lean replacement for the bdc_availability_tbl created by schema.sql.
--
-- WHY THIS EXISTS
--
-- MEASURED, by loading Rhode Island and Delaware entire into PostgreSQL 16:
-- 2,757,622 real rows took 746 MB, being 583 MB of heap and 163 MB of
-- indexes. That is 283.8 bytes per row. At the observed 200,000 rows per
-- zipped megabyte, the 4.06 GB of non-satellite national data is on the order
-- of 810 million rows, so about 230 GB.
--
-- Most of that is repetition rather than data. The columns below are the same
-- information; what changes is that the three values repeated on every single
-- row, being the file name, the carrier identity and the derived geographies,
-- are stored once each and referenced.
--
--
-- THIS FILE REFUSES TO RUN IF THERE IS ANYTHING TO LOSE
--
-- It DROPS and recreates bdc_availability_tbl. The guard below counts the
-- rows first and raises an exception if there are any, so the destructive
-- path is reachable only on an empty table.
--
-- PRE-MORTEM for the drop, in the only case where it proceeds: the table is
-- empty, so no availability data exists to lose. The decision-log tables
-- geo_decision_run and geo_decision_log are NOT touched by this file at all.
-- Nothing else in the database is referenced. If the table does hold rows,
-- the exception names the two ways forward and nothing is dropped.
--
-- If you would rather keep the wide table, do not run this file. schema.sql
-- is still correct and still works; this is a size trade, not a fix.


-- The rename of bdc_provider_tbl to bdc_carrier_tbl lives in
-- geo/fcc_bdc/rename_provider_to_carrier.sql, which renames and nothing
-- else. It is NOT here because this file drops and truncates, and a rename
-- should never require running a file that can also empty a table.

-- ---------------------------------------------------------------------------
-- GUARD
-- ---------------------------------------------------------------------------

DO $$
DECLARE
    n bigint;
BEGIN
    IF to_regclass('bdc_availability_tbl') IS NULL THEN
        RAISE NOTICE 'bdc_availability_tbl does not exist yet; creating the lean schema from scratch.';
        RETURN;
    END IF;

    EXECUTE 'SELECT count(*) FROM bdc_availability_tbl' INTO n;

    IF n > 0 THEN
        RAISE EXCEPTION
            'bdc_availability_tbl holds % rows and this file would DROP it. Nothing has been changed. Either (a) keep the current schema and do not run this file, or (b) if those rows are reloadable from the downloads in the data directory, drop the table yourself and re-run this file, then reload with bdc_load.py.', n;
    END IF;

    RAISE NOTICE 'bdc_availability_tbl exists and is empty, so replacing it loses nothing.';
END
$$;


-- ---------------------------------------------------------------------------
-- THE FILE A ROW CAME FROM, STORED ONCE
--
-- Was a text column repeating a 58-character file name on every row, which
-- at 810 million rows is roughly 46 GB to say one of 333 things.
--
-- smallint, not integer: 442 files per vintage and four vintages published so
-- far, so a few thousand at most against a 32,767 ceiling.
-- ---------------------------------------------------------------------------

-- A LOCK TIMEOUT. This file issues DDL, and DDL takes ACCESS EXCLUSIVE.
-- A WAITING AccessExclusiveLock request blocks every later lock request on
-- that table, so a queued DDL statement stalls writers as well as itself.
-- On 2026-11-17 a rename queued behind a running bdc_load.py and blocked it.
-- Five seconds is ample for an idle table and refuses to queue behind a busy
-- one.
SET lock_timeout = '5s';
SET statement_timeout = '10min';

CREATE TABLE IF NOT EXISTS bdc_source_file_tbl (
    source_file_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file    text        NOT NULL UNIQUE,
    loaded_at      timestamptz NOT NULL DEFAULT now(),
    row_count      bigint
);

COMMENT ON TABLE bdc_source_file_tbl IS
    'One row per downloaded availability file. Holds the name and load time that were previously repeated on every availability row. row_count is what bdc_load.py inserted from it, so a partial load is visible without counting the big table.';


-- ---------------------------------------------------------------------------
-- THE CARRIER, STORED ONCE
--
-- frn, provider_id and brand_name identify a filer and are repeated on every
-- row. There are a few thousand providers nationally against hundreds of
-- millions of rows, so the three together cost roughly 33 bytes per row to
-- say one of a few thousand things.
--
-- The three are kept TOGETHER as the key rather than collapsed to
-- provider_id, because one provider_id can file under several brand names
-- and the brand is part of what distinguishes a network. Verizon fibre and
-- Verizon fixed wireless share a provider_id and are separated by technology;
-- other carriers separate by brand.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS bdc_carrier_tbl (
    carrier_key serial      PRIMARY KEY,
    frn          text,
    provider_id  integer,
    brand_name   text,
    UNIQUE (frn, provider_id, brand_name)
);

COMMENT ON TABLE bdc_carrier_tbl IS
    'One row per distinct filer identity, being the combination of FRN, FCC provider_id and consumer brand name. Referenced by bdc_availability_tbl so those three values are stored once rather than on every availability row.';
COMMENT ON COLUMN bdc_carrier_tbl.brand_name IS
    'Part of the key, not a label: one provider_id can file under several brands, and the brand distinguishes networks that technology alone does not.';


-- ---------------------------------------------------------------------------
-- AVAILABILITY
--
-- What was dropped against schema.sql, and why each is safe:
--
--   bdc_id        a bigserial primary key that nothing referenced. 8 bytes
--                 per row plus its index.
--   loaded_at     moved to bdc_source_file_tbl, where it belongs: every row
--                 from one file was loaded at the same moment.
--   source_file   replaced by source_file_id.
--   frn,          replaced by carrier_key.
--   provider_id,
--   brand_name
--   state_fips    derivable as left(block_geoid, 2), and state_usps already
--                 carries the state on the row.
--   county_geoid  derivable as left(block_geoid, 5). Used by nothing yet.
--
-- tract_geoid IS KEPT as a generated column. It is the join key for steps 4
-- to 7 and the thing most queries group by, and generating it means it cannot
-- be computed two different ways at two call sites.
--
-- block_geoid IS STILL TEXT UNDER A 15-DIGIT CHECK. That is not a size
-- decision and it is not negotiable: it is a fixed-width code and about half
-- the states carry a leading zero, Alabama being 01, so reading it as a
-- number misfiles an entire state. Verified against the real constraint.
-- ---------------------------------------------------------------------------

-- The view defined at the foot of this file depends on the table, so on a
-- SECOND run of this file the DROP below fails with "cannot drop table
-- bdc_availability_tbl because other objects depend on it". Dropping the view
-- first is what makes the file re-runnable. Found by running it twice.
DROP VIEW IF EXISTS bdc_availability;

DROP TABLE IF EXISTS bdc_availability_tbl;

-- The availability table has just been emptied, so the record of which files
-- were loaded and how many rows each contributed now describes nothing. It
-- is cleared for the same reason, and it is safe to clear precisely because
-- the only table that referenced these rows no longer exists. Both are
-- rebuilt by bdc_load.py from the files themselves.
-- Report what is about to be emptied, with counts. This statement is
-- reachable only when the guard above found bdc_availability_tbl empty, so
-- these two tables describe nothing, but a silent TRUNCATE of a table
-- holding 1,802 carriers is not something to discover afterwards.
DO $$
DECLARE c bigint; f bigint;
BEGIN
    SELECT count(*) INTO c FROM bdc_carrier_tbl;
    SELECT count(*) INTO f FROM bdc_source_file_tbl;
    IF c > 0 OR f > 0 THEN
        RAISE NOTICE 'About to TRUNCATE bdc_carrier_tbl (% rows) and bdc_source_file_tbl (% rows). They are rebuilt by bdc_load.py from the downloads, and the availability table they describe is empty, so they currently describe nothing.', c, f;
    END IF;
END
$$;

TRUNCATE bdc_source_file_tbl, bdc_carrier_tbl RESTART IDENTITY;

CREATE TABLE bdc_availability_tbl (
    source_file_id smallint NOT NULL
        REFERENCES bdc_source_file_tbl (source_file_id),
    carrier_key   integer  NOT NULL
        REFERENCES bdc_carrier_tbl (carrier_key),

    location_id    bigint,
    technology     smallint,

    max_advertised_download_speed integer,
    max_advertised_upload_speed   integer,
    low_latency                   smallint,
    business_residential_code     text,

    state_usps     text,
    block_geoid    text NOT NULL,
    h3_res8_id     text,

    tract_geoid    text GENERATED ALWAYS AS (left(block_geoid, 11)) STORED,

    CONSTRAINT bdc_block_geoid_is_15_digits
        CHECK (block_geoid ~ '^[0-9]{15}$')
);

CREATE INDEX IF NOT EXISTS bdc_availability_tract_idx
    ON bdc_availability_tbl (tract_geoid);
CREATE INDEX IF NOT EXISTS bdc_availability_provider_tech_idx
    ON bdc_availability_tbl (carrier_key, technology);
CREATE INDEX IF NOT EXISTS bdc_availability_source_file_idx
    ON bdc_availability_tbl (source_file_id);

-- NOT created, against schema.sql: indexes on block_geoid and on h3_res8_id.
-- Together they were a fifth of the index volume and no step written so far
-- reads either. CREATE INDEX on a populated table is a few minutes, so
-- adding one later when a query needs it is cheap; carrying it through a
-- national load is not.

COMMENT ON TABLE bdc_availability_tbl IS
    'FCC Broadband Data Collection fixed availability, from the PUBLIC per-state per-technology downloads. One row per filed availability record. Carrier and source file are referenced rather than repeated; see bdc_carrier_tbl and bdc_source_file_tbl.';
COMMENT ON COLUMN bdc_availability_tbl.block_geoid IS
    'Census block GEOID, 15 characters, TEXT so leading zeros survive. State FIPS is characters 1-2, county 1-5, tract 1-11. Storing it as a number misfiles every state whose FIPS begins with a zero.';
COMMENT ON COLUMN bdc_availability_tbl.technology IS
    'FCC technology code. The mapping to names comes from the FCC download catalogue, written out by bdc_fetch.py as bdc_technology_codes.tsv, and is not hardcoded in this project.';


-- ---------------------------------------------------------------------------
-- A VIEW WITH THE OLD SHAPE
--
-- So that anything written against the wide table, and any query that is
-- simply easier to read with the names spelled out, keeps working. Costs
-- nothing on disk.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE VIEW bdc_availability AS
SELECT a.source_file_id,
       f.source_file,
       f.loaded_at,
       p.frn,
       p.provider_id,
       p.brand_name,
       a.location_id,
       a.technology,
       a.max_advertised_download_speed,
       a.max_advertised_upload_speed,
       a.low_latency,
       a.business_residential_code,
       a.state_usps,
       a.block_geoid,
       a.h3_res8_id,
       left(a.block_geoid, 2)  AS state_fips,
       left(a.block_geoid, 5)  AS county_geoid,
       a.tract_geoid
FROM bdc_availability_tbl a
JOIN bdc_source_file_tbl  f USING (source_file_id)
JOIN bdc_carrier_tbl     p USING (carrier_key);

COMMENT ON VIEW bdc_availability IS
    'bdc_availability_tbl with the file name, carrier identity and derived geographies spelled out, so queries written against the earlier wide table still work. state_fips and county_geoid are computed here rather than stored.';
